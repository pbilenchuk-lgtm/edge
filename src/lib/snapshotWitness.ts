// EDGE LAB — N7: «0 СНАПШОТОВ» ПЕРЕСТАЁТ ОБВИНЯТЬ МАППИНГ В ТОМ, ЧТО СДЕЛАЛ РЕТЕНШН
//
// ИМЕННОЙ КЕЙС: 115 матч-логов печатали «скаут не привязал матч (0 снапшотов tennis_snapshots) — маппинг
// имён не сошёлся или скаут не видит матч live». Предикат за этим утверждением — `COUNT(*) = 0` по
// `tennis_snapshots`. Таблица живёт под ГЛОБАЛЬНЫМ 20k-кэпом (~20 строк каждые 20 секунд) плюс 5-дневный
// time-prune. Кэп режет по времени и по всей таблице сразу, поэтому густо снятый вчера матч и матч,
// которого провайдер не видел вовсе, дают ОДИН И ТОТ ЖЕ ноль. Диагноз называл причиной провал маппинга и
// вёл лечение не туда — 115 раз.
//
// Это ровно класс O8 («источник живёт короче архива»), только применённый не к вердикту, а к диагнозу:
// факт «снимок был» материализуется В МОМЕНТ ЗАПИСИ (persistent-счётчик на матче, см. repo.noteSnapshotWitness),
// а не вычисляется потом из источника, который к тому моменту испарился. Кэп не поднимается: он стоит не
// по прихоти — таблица однажды раздулась до 1.2 ГБ и заморозила загрузку.
//
// ТРИ СОСТОЯНИЯ ВМЕСТО ОДНОГО НУЛЯ:
//   never   — счётчик 0 и матч заведён ПОСЛЕ появления свидетеля ⇒ снимков не было никогда (фид/привязка);
//   wiped   — счётчик > 0, живых строк нет ⇒ БЫЛИ и стёрты ретеншном (обвинять маппинг — ложь);
//   present — живые строки есть ⇒ штатно;
//   unknown — счётчик 0, но матч старше свидетеля ⇒ ОТВЕТА НЕТ. Бэкфилла быть не может (прошлые записи не
//             восстановить), и молчать здесь честнее, чем повторять прежнее обвинение под новым именем.
//
// `unknown` вымрет сам: он возможен только для матчей, живших до деплоя колонки.
// ============================================================

import type { Database } from "./db.js";
import * as R from "./repo.js";

export type SnapshotWitnessVerdict = "present" | "wiped" | "never" | "unknown";

export interface SnapshotWitness {
  verdict: SnapshotWitnessVerdict;
  seenTotal: number;      // сколько снимков БЫЛО записано за всю жизнь матча (не уменьшается)
  liveRows: number;       // сколько строк живо СЕЙЧАС (то, что видел прежний диагноз)
  firstAt: string | null;
  lastAt: string | null;
  note: string;           // причина словами — без обвинений, которых улики не выдерживают
}

/** Момент, начиная с которого счётчик достоверен: матч, заведённый раньше, счётчика не имел. */
function witnessBornAt(db: Database): string | null {
  try {
    const r = db.prepare(`SELECT MIN(snapshots_first_at) f FROM matches WHERE snapshots_first_at IS NOT NULL`).get() as { f?: string | null } | undefined;
    return r?.f ?? null;
  } catch { return null; }
}

/**
 * Классифицировать «почему снимков нет» для одного матча.
 * `liveRows` передаёт вызывающий — он же считает их своим запросом (теннис/футбол разные таблицы),
 * и второй счётчик здесь был бы вторым авторитетом на тот же вопрос.
 */
export function snapshotWitness(db: Database, matchId: string, liveRows: number, createdHint?: string | null): SnapshotWitness {
  const w = R.snapshotWitnessFor(db, matchId);
  const base = { seenTotal: w.seenTotal, liveRows, firstAt: w.firstAt, lastAt: w.lastAt };
  if (liveRows > 0) {
    return { ...base, verdict: "present", note: `снимки на месте: живых строк ${liveRows}, записано за всю жизнь ${w.seenTotal}` };
  }
  if (w.seenTotal > 0) {
    return {
      ...base, verdict: "wiped",
      note: `снимки БЫЛИ (${w.seenTotal} записей${w.lastAt ? `, последняя ${w.lastAt}` : ""}) и стёрты ретеншном —`
        + ` живых строк 0. Привязка сработала; «маппинг не сошёлся» здесь было бы ложным обвинением`,
    };
  }
  const born = witnessBornAt(db);
  const anchor = createdHint ?? null;
  if (born && anchor && anchor < born) {
    return {
      ...base, verdict: "unknown",
      note: `снимков не видно, но матч старше счётчика-свидетеля (он ведётся с ${born}) — ответа нет.`
        + ` Бэкфилл невозможен: стёртые строки не восстановить, а повторить прежнее обвинение значило бы выдать незнание за факт`,
    };
  }
  return {
    ...base, verdict: "never",
    note: `снимков не было НИКОГДА (счётчик-свидетель 0 за всю жизнь матча) — привязка не сошлась либо провайдер матч не отдавал`,
  };
}

/** Короткая строка для матч-лога/отчётов. */
export function witnessLine(w: SnapshotWitness): string {
  return `снимки: живых ${w.liveRows} · записано за жизнь ${w.seenTotal} · ${w.verdict} — ${w.note}`;
}
