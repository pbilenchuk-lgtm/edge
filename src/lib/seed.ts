export function migrateSeedStrategists(db: Database, now: string): void {
  // strategies.sport_id has an FK to sports(id); on a brand-new DB the sport row
  // may not exist yet at boot, which would FK-throw and leave the roster missing.
  R.upsertSport(db, "football", SPORT_LABELS["football"] ?? "Футбол");
  for (const d of STRATEGIST_DEFS) {
    if (R.getStrategy(db, d.id)) continue;
    R.insertStrategy(db, { id: d.id, sport_id: "football", name: d.name, tag: d.tag, color: d.color, version: 1, model: "Claude Opus 4.8", created_at: now, prompt: d.prompt, prompt_live: d.prompt_live, params: {} });
  }
}

// One-time roster transition: retire the legacy single strategy ("wc") and put
// the three real strategists on EVERY existing competition at the MEDIUM profile,
// split evenly. Gated on "wc" still existing, so it runs exactly once (after it,
// wc is gone and the guard is false). Non-recurring, so it never clobbers the
// user's later manual allocations. New competitions discovered afterwards are
// assigned by the user (this migration only touches what exists at transition).
const LEGACY_STRATEGY_ID = "wc";
export function migrateStrategyRoster(db: Database, now: string): void {
  migrateSeedStrategists(db, now); // always ensure the three exist
  if (!R.getStrategy(db, LEGACY_STRATEGY_ID)) return; // already transitioned
  const trio = STRATEGIST_DEFS.map((d) => d.id);
  const pcts = [34, 33, 33]; // even thirds, sum 100
  for (const c of R.listCompetitions(db)) {
    R.clearShares(db, c.id);
    trio.forEach((sid, i) => R.setShare(db, { competition_id: c.id, strategy_id: sid, risk_profile_id: "aggressive", pct: pcts[i] }));
  }
  R.deleteStrategy(db, LEGACY_STRATEGY_ID); // removes wc + its shares/bets/versions everywhere
}

// One-time reassignment: put EVERY (category × strategy) allocation onto the
// AGGRESSIVE risk profile, so strategies are simulated at their boldest (lower
// min-edge, bigger Kelly, wider stops, later take-profit). Guarded by a persistent
// marker so it runs exactly once and never clobbers the user's later manual
// profile picks. Per competition, collapse each strategy's shares to a single
// aggressive row (summing pct across any prior profiles → total budget preserved),
// then retag still-live bets so their exits use the aggressive thresholds too.
const AGGRESSIVE_MARK = "shares_aggressive_v1";
export function migrateSharesToAggressive(db: Database, now: string): void {
  if (R.metaGet(db, AGGRESSIVE_MARK)) return;
  for (const c of R.listCompetitions(db)) {
    const shares = R.sharesForComp(db, c.id);
    if (!shares.length) continue;
    const byStrat = new Map<string, number>();
    for (const s of shares) byStrat.set(s.strategy_id, (byStrat.get(s.strategy_id) ?? 0) + s.pct);
    R.clearShares(db, c.id);
    for (const [sid, pct] of byStrat)
      R.setShare(db, { competition_id: c.id, strategy_id: sid, risk_profile_id: "aggressive", pct });
  }
  // Retag open/proposed positions so their live exits read the aggressive profile;
  // settled bets keep their historical tag (don't rewrite realized P&L).
  db.prepare(`UPDATE bets SET risk_profile_id='aggressive' WHERE status IN ('open','proposed')`).run();
  R.metaSet(db, AGGRESSIVE_MARK, now, now);
}

// One-time: put the FULL grid of pairs on every football category — all 3
// strategists × all 3 risk profiles = 9 pairs, funds split evenly — so every
// (strategy, profile) combination is simulated side by side. Marker-guarded:
// runs once, then respects any later manual reallocation. Supersedes the
// aggressive-only assignment above (runs after it in boot order).
const ALL_PAIRS_MARK = "shares_all_pairs_v1";
export function migrateSharesAllPairs(db: Database, now: string): void {
  if (R.metaGet(db, ALL_PAIRS_MARK)) return;
  migrateSeedStrategists(db, now); // ensure the trio exists
  const strategyIds = STRATEGIST_DEFS.map((d) => d.id);           // 3
  const profileIds = RISK_PROFILE_DEFS.map((p) => p.id);          // aggressive/medium/conservative
  const n = strategyIds.length * profileIds.length;               // 9
  const pct = Math.round(10000 / n) / 100;                        // even split → 11.11% each
  for (const c of R.listCompetitions(db)) {
    if (c.sport_id !== "football") continue;
    R.clearShares(db, c.id);
    for (const sid of strategyIds)
      for (const pid of profileIds)
        R.setShare(db, { competition_id: c.id, strategy_id: sid, risk_profile_id: pid, pct });
  }
  R.metaSet(db, ALL_PAIRS_MARK, now, now);
}

// Keep the full grid current as the PROFILE SET changes: every football category
// carries all strategists × ALL risk profiles present in the DB (incl. custom
// ones the user adds), funds split evenly. Unlike the v1 pass above this reads
// the profiles from the DB, and its marker is the profile-set signature — so it
// re-lays the grid (3×N pairs, even) whenever a profile is added/removed, and
// otherwise no-ops (a stable set → manual reallocations survive). This is what
// makes «I added a profile → put it on every strategy in every category, equal
// budget» happen automatically.
const GRID_MARK = "shares_grid_signature";
const PER_PAIR_USD = 1000; // every (strategy, profile) pair is funded with this, on every football category
export function migrateSharesGrid(db: Database, now: string): void {
  migrateSeedStrategists(db, now);
  const strategyIds = STRATEGIST_DEFS.map((d) => d.id);
  const profileIds = listRiskProfileViews(db).map((p) => p.id).sort();
  if (!strategyIds.length || !profileIds.length) return;
  const n = strategyIds.length * profileIds.length;
  // Signature includes the per-pair target, so introducing/altering budget
  // management re-lays the grid even if the profile SET is unchanged.
  const signature = `${PER_PAIR_USD}|${profileIds.join(",")}`;
  if (R.metaGet(db, GRID_MARK) === signature) return; // nothing changed → leave allocations/budget alone
  // Full-precision even split: pct=100/n with budget=n·PER_PAIR floors to EXACTLY
  // PER_PAIR per pair (money.stratBudget = floor(budget·pct/100)); display rounds it.
  const pct = 100 / n;
  const budget = n * PER_PAIR_USD;
  for (const c of R.listCompetitions(db)) {
    if (c.sport_id !== "football") continue;
    R.setCompetitionBudget(db, c.id, budget); // e.g. 12 pairs → $12 000 → $1 000 each
    R.clearShares(db, c.id);
    for (const sid of strategyIds)
      for (const pid of profileIds)
        R.setShare(db, { competition_id: c.id, strategy_id: sid, risk_profile_id: pid, pct });
  }
  R.metaSet(db, GRID_MARK, signature, now);
}
