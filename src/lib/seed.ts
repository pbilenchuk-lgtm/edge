/**
 * Clean-start seed for a real deployment. Bakes in the user's ЧМ-2026 default
 * analysis prompts + the THREE real two-phase strategists (each with a предматч
 * and a live prompt). Real categories/matches arrive from "Подтянуть матчи" and
 * the cron. This is what the production container seeds on first boot.
 */
export function seedMinimal(db: Database): void {
  // NON-DESTRUCTIVE + idempotent. If the DB already holds data (treasury row
  // present), do nothing — NEVER wipe a user's live state by reseeding. This
  // used to `DELETE FROM` every table first, so any run against a populated DB
  // (a boot where the file survived, an accidental re-invocation, a future
  // migration) erased bets / budgets / API keys / analysis history. First-boot
  // detection also lives in start.sh (seed only when the file is absent); this
  // guard is the belt-and-suspenders so seeding can never destroy data.
  const seeded = db.prepare(`SELECT 1 FROM treasury LIMIT 1`).get();
  if (seeded) return;

  R.setTreasury(db, 5000); // starting bankroll — editable on the Настройки screen
  for (const [id, label] of Object.entries(SPORT_LABELS)) R.upsertSport(db, id, label);

  // Analytics: Промпт 1 at sport level (all football), Промпт 2 as the ЧМ-2026
  // competition override — analyticsPromptFor concatenates them for WC matches.
  R.upsertAnalyticsPrompt(db, "sport", "football", PROMPT_MATCH_ANALYTICS, "Claude Opus 4.8");
  R.upsertAnalyticsPrompt(db, "competition", "pm-soccer-fifwc", PROMPT_WC_CONTEXT, null);

  // The two real two-phase strategists. Sizing/edge/caps come from the assigned
  // risk profile (risk_config), not per-strategy params — so params stay empty;
  // the strategist LLM only writes the plan (code does the money math).
  R.insertStrategy(db, {
    id: "overreaction", sport_id: "football", name: "Overreaction", tag: "выкуп переоценки", color: "#e8a838",
    version: 1, model: "Claude Opus 4.8", created_at: T,
    prompt: STRAT_OVERREACTION_PREMATCH, prompt_live: STRAT_OVERREACTION_LIVE, params: {},
  });
  R.insertStrategy(db, {
    id: "prematch_value", sport_id: "football", name: "Pre-match Value", tag: "предматч value", color: "#5b9bd5",
    version: 1, model: "Claude Opus 4.8", created_at: T,
    prompt: STRAT_PMVALUE_PREMATCH, prompt_live: STRAT_PMVALUE_LIVE, params: {},
  });
  R.insertStrategy(db, {
    id: "live_xg", sport_id: "football", name: "Live xG Momentum", tag: "live xG", color: "#70b56a",
    version: 1, model: "Claude Opus 4.8", created_at: T,
    prompt: STRAT_LIVEXG_PREMATCH, prompt_live: STRAT_LIVEXG_LIVE, params: {},
  });

  // Named risk presets (aggressive/medium/conservative) — a competition assigns
  // (strategy, profile) pairs. MEDIUM is the reference for testing strategists.
  seedRiskProfiles(db, T);
}

